a = -7
b = 2.6789
c, d = 17, 5

print(abs(a))        # Giá trị tuyệt đối của a: 7
print(round(b))      # Làm tròn b về số nguyên gần nhất: 3
print(round(b, 2))   # Làm tròn b lấy 2 chữ số thập phân: 2.68
print(pow(c, 2))     # Tính c mũ 2: 289
print(divmod(c, d))  # Trả về cặp (thương, dư) dạng tuple: (3, 2)